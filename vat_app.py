import streamlit as st

# 1. แสดงชื่อแอปพลิเคชัน
st.title("🛒 แอปพลิเคชันคำนวณราคาสินค้ารวม VAT 7%")

# 2. สร้างช่องรับข้อมูลตัวเลขราคาสินค้า
price = st.number_input("กรอกราคาสินค้า (บาท):", value=0.0)

# 3. คำนวณ VAT 7% และราคาสุทธิ (แก้ไขเครื่องหมาย + ให้ถูกต้องแล้ว)
vat = price * 0.07
net_price = price + vat

# 4. แสดงผลการคำนวณ
st.header(f"• ภาษีมูลค่าเพิ่ม (VAT 7%): **{vat:.2f}** บาท")
st.header(f"• ราคาสุทธิ: {net_price:.2f} บาท")

# 5. สร้างเส้นกั้น
st.divider()

# 6. แสดงข้อมูลผู้จัดทำ
st.write("นางสาวกนกพิญ์ วชิรโกวิทย์ เลขที่ 23 ม.4/3")
